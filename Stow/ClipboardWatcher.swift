import AppKit

/// Clipboard history: while the setting is on, everything you copy (text, links,
/// images, files) goes into a "Clipboard" stack on the shelf, newest first, keeping
/// the last `limit`.
///
/// macOS has no "clipboard changed" notification, so this checks the clipboard's
/// change count a few times a second, which costs nothing. It only reads the
/// clipboard when the count moves. macOS 26 asks once whether Stow may paste from
/// other apps; choosing Allow makes that permanent.
///
/// Things password managers and similar apps mark as secret or temporary
/// (nspasteboard.org's concealed, transient and auto-generated types) are never
/// read, and neither is what Stow itself copied.
final class ClipboardWatcher {
    static let limit = 15

    /// Put on the clipboard alongside whatever Stow copies, so the watcher can
    /// skip it without reading anything.
    private static let stowMarker = NSPasteboard.PasteboardType("com.aaryanjigarpanchal.Stow.copied")
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        stowMarker,
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        // Older password managers' markers.
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
    ]

    private let viewModel: ShelfViewModel
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    init(viewModel: ShelfViewModel) {
        self.viewModel = viewModel
    }

    /// Marks what Stow just put on the clipboard as Stow's own.
    static func markAsStows(_ pasteboard: NSPasteboard) {
        pasteboard.setData(Data(), forType: stowMarker)
    }

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        // Only what's copied from now on, not what was already there.
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        // Looking at the types reads no data and never asks for permission.
        guard let types = pasteboard.types, !types.isEmpty, Set(types).isDisjoint(with: Self.skippedTypes) else { return }
        guard PasteboardContents.offersAcceptedTypes(pasteboard) else { return }
        let incoming = PasteboardContents.read(from: pasteboard)
        guard !incoming.isEmpty else { return }
        viewModel.addClipboardEntries(incoming, limit: Self.limit)
    }
}
